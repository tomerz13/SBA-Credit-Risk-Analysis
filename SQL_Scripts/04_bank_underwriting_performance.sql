-- ==============================================================================
-- Query 04: Bank Underwriting Performance
-- Purpose: Evaluate which banks have the highest default rates, indicating 
--          potential risk in their loan approval (underwriting) processes.
-- Note:    Utilizes 'vw_clean_loan_data' for pre-cleaned and formatted data.
-- ==============================================================================

SELECT TOP 20
    Bank_Name,
    
    -- 1. Total volume of loans approved by this bank
    COUNT(*) AS Total_Approved_Loans,
    
    -- 2. Number of those loans that defaulted
    SUM(CASE WHEN Loan_Status = 'CHGOFF' THEN 1 ELSE 0 END) AS Defaulted_Loans,
    
    -- 3. Calculate the Bank's Default Rate (%)
    ROUND(
        CAST(SUM(CASE WHEN Loan_Status = 'CHGOFF' THEN 1 ELSE 0 END) AS FLOAT) 
        / COUNT(*) * 100, 2
    ) AS Default_Rate_Percentage,
    
    -- 4. Calculate the total financial loss generated by this bank's bad loans
    SUM(CASE WHEN Loan_Status = 'CHGOFF' THEN Charge_Off_Amount ELSE 0 END) AS Total_Financial_Loss

FROM 
    vw_clean_loan_data

WHERE 
    Bank_Name IS NOT NULL

GROUP BY 
    Bank_Name

ORDER BY 
    Default_Rate_Percentage DESC;